// Fetches the narration from ElevenLabs ONCE per line and keeps it in assets/vo/ (committed), so re-renders
// cost no credits. Uses the /with-timestamps endpoint: the character alignment gives exact word times for
// captions. Then writes vo-data.js (durations + word times) for score.js / film.js.
//   ELEVENLABS_API_KEY=... node tts.js            fetch missing lines, rebuild vo-data.js
//   node tts.js --only hook                       fetch just one line (e.g. to test cost / voice)
const fs = require('fs');
const path = require('path');
const { execFileSync } = require('child_process');
const LINES = require('./lines');

const VOICE = process.env.ELEVENLABS_VOICE_ID || 'zfc8CJQpe8Kqyl0vvCzo'; // Mike - 2D & 3D POV/Storytime
const MODEL = process.env.ELEVENLABS_MODEL || 'eleven_flash_v2_5'; // half the credits of multilingual_v2
const DIR = path.join(__dirname, 'assets', 'vo');
fs.mkdirSync(DIR, { recursive: true });
const only = process.argv.includes('--only') ? process.argv[process.argv.indexOf('--only') + 1] : null;

function fetchLine(l) {
  const key = process.env.ELEVENLABS_API_KEY;
  if (!key) throw new Error('ELEVENLABS_API_KEY not set');
  const body = JSON.stringify({
    text: l.say, model_id: MODEL,
    voice_settings: { stability: 0.4, similarity_boost: 0.8, style: 0.35, use_speaker_boost: true, speed: 1.04 },
  });
  const url = `https://api.elevenlabs.io/v1/text-to-speech/${VOICE}/with-timestamps?output_format=mp3_44100_128`;
  const out = execFileSync('curl', ['-sS', '--fail-with-body', '-X', 'POST', url, '-H', `xi-api-key: ${key}`,
    '-H', 'Content-Type: application/json', '--data-binary', '@-'], { input: body, maxBuffer: 64 << 20 }).toString();
  const r = JSON.parse(out);
  if (!r.audio_base64) throw new Error('ElevenLabs: ' + out.slice(0, 300));
  fs.writeFileSync(path.join(DIR, l.id + '.mp3'), Buffer.from(r.audio_base64, 'base64'));
  fs.writeFileSync(path.join(DIR, l.id + '.json'), JSON.stringify({ say: l.say, voice: VOICE, model: MODEL, alignment: r.alignment }));
  console.log('  elevenlabs:', l.id, `(${l.say.length} chars)`);
}

// word times from the character alignment
function words(al) {
  const ws = [];
  let cur = null;
  al.characters.forEach((c, i) => {
    if (/\s/.test(c)) { if (cur) ws.push(cur); cur = null; return; }
    if (!cur) cur = { w: '', t: al.character_start_times_seconds[i], end: 0 };
    cur.w += c; cur.end = al.character_end_times_seconds[i];
  });
  if (cur) ws.push(cur);
  return ws;
}

function duration(file) {
  return parseFloat(execFileSync('ffprobe', ['-v', 'error', '-show_entries', 'format=duration', '-of', 'csv=p=0', file]).toString());
}

for (const l of LINES) {
  if (only && l.id !== only) continue;
  const j = path.join(DIR, l.id + '.json');
  if (fs.existsSync(j) && JSON.parse(fs.readFileSync(j, 'utf8')).say === l.say) continue;
  fetchLine(l);
}

const data = {};
for (const l of LINES) {
  const j = path.join(DIR, l.id + '.json');
  if (!fs.existsSync(j)) continue;
  const meta = JSON.parse(fs.readFileSync(j, 'utf8'));
  const ws = words(meta.alignment);
  const capw = l.cap.split(/\s+/);
  if (capw.length !== ws.length) throw new Error(`${l.id}: caption has ${capw.length} words, speech has ${ws.length}`);
  // the voice clip is trimmed at the first / last word in song.js: store times relative to the first word
  const t0 = Math.max(0, ws[0].t - 0.03);
  const dur = Math.min(duration(path.join(DIR, l.id + '.mp3')) - t0, ws[ws.length - 1].end - t0 + 0.12);
  const out = [];
  ws.forEach((w, i) => {
    if (capw[i] === '~') { out[out.length - 1].end = +(w.end - t0).toFixed(3); return; }
    out.push({ w: capw[i], t: +(w.t - t0).toFixed(3), end: +(w.end - t0).toFixed(3) });
  });
  data[l.id] = { t0: +t0.toFixed(3), dur: +dur.toFixed(3), words: out };
}
fs.writeFileSync(path.join(__dirname, 'vo-data.js'),
  `// generated by tts.js from assets/vo/*.json — do not edit\n(function () {\n  const VO = ${JSON.stringify(data)};\n  if (typeof module !== 'undefined') module.exports = VO; else globalThis.VODATA = VO;\n})();\n`);
console.log('vo-data.js:', Object.entries(data).map(([k, v]) => `${k} ${v.dur.toFixed(2)}s`).join(', '));
