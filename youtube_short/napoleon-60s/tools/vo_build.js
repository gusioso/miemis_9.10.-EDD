// Builds the voice track and the word timing from assets/vo/*.wav (made by tools/make_vo.py).
//   node tools/vo_build.js  -> out/vo.wav (one mixed, levelled voice track), out/voice.json, assets/vo/timing.js
// timing.js is read by score.js (animation) and song.js (music ducking) so picture and sound share one timeline.
const fs = require('fs');
const path = require('path');
const { SR, Bus, OnePole } = require('../engine/audio/dsp');
const Voice = require('../engine/audio/voice');
const MIX = require('../engine/audio/mix');

const root = path.join(__dirname, '..');
const plan = JSON.parse(fs.readFileSync(path.join(root, 'assets/vo/plan.json'), 'utf8'));
const LENGTH = 60;
const bus = new Bus(Math.ceil(LENGTH * SR));
const hp = new OnePole();
const lines = [];
for (const L of plan) {
  const audio = Voice.decode(path.join(root, 'assets/vo', L.id + '.wav'));
  // fit the words of each spoken part inside that part's own stretch of audio
  const fitted = [];
  for (const P of L.parts) {
    const words = P.show.split(/\s+/).filter((w) => /[\p{L}\p{N}]/u.test(w));
    const seg = audio.subarray(Math.round(P.t0 * SR), Math.round(P.t1 * SR));
    for (const w of Voice.fit(seg, words, null)) fitted.push({ w: w.w, t: +(L.at + P.t0 + w.t).toFixed(3), end: +(L.at + P.t0 + w.end).toFixed(3) });
  }
  let s = 0, c = 0;
  for (let i = 0; i < audio.length; i++) if (Math.abs(audio[i]) > 0.01) { s += audio[i] * audio[i]; c++; }
  const g = c ? Math.min(6, 0.13 / Math.sqrt(s / c)) : 1;
  const x = new Float32Array(audio.length);
  for (let i = 0; i < x.length; i++) x[i] = hp.hp(audio[i] * g, 85);
  bus.addMono(x, L.at, 1);
  lines.push({ id: L.id, t: L.at, end: +(L.at + audio.length / SR).toFixed(3), text: L.parts.map((P) => P.show).join(' '), words: fitted });
}
fs.mkdirSync(path.join(root, 'out'), { recursive: true });
MIX.writeWav(path.join(root, 'out/vo.wav'), bus);
const vo = { engine: 'kokoro-onnx am_liam', lines, mouth: Voice.mouthTrack(bus, 30) };
fs.writeFileSync(path.join(root, 'out/voice.json'), JSON.stringify(vo));
fs.writeFileSync(path.join(root, 'assets/vo/timing.js'),
  `// generated by tools/vo_build.js: narration line and word times (seconds)\n(function () {\n  const V = ${JSON.stringify({ lines }, null, 1)};\n  if (typeof module !== 'undefined') module.exports = V; else globalThis.VOT = V;\n})();\n`);
console.log('voice: ' + lines.map((l) => `${l.id} ${l.t.toFixed(2)}-${l.end.toFixed(2)}`).join('  '));
